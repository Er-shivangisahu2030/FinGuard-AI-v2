suffixes = [
 ' This happened yesterday and I am concerned about the money involved.',
 ' I have already checked the official app but I still need assistance.',
 ' I am not sure whether the message or request was genuine.',
 ' I would like the transaction or account activity to be reviewed.',
 ' I kept the message and transaction details for reference.',
 ' The amount involved was around INR {amount}.',
 ' I did not knowingly approve this action.',
 ' I contacted support but have not received a clear resolution.'
]
methods = ['UPI','Debit Card','Credit Card','Net Banking','Wallet','Bank Transfer']

def synth_text(category, i):
    base = random.choice(subjects[category])
    amount = random.choice([350, 799, 1200, 2500, 4999, 8500, 15000, 32000])
    suffix = random.choice(suffixes).format(amount=amount)
    text = base + suffix
    # Add modest natural noise so the model does not learn one rigid phrase per label.
    if i % 17 == 0:
        text = text.replace('payment', 'pymnt')
    if i % 29 == 0:
        text = text.replace('account', 'acct')
    if i % 41 == 0:
        text = text.replace('I ', 'i ', 1)
    return text, amount

rows=[]
per_category=300
for category in subjects:
    for i in range(per_category):
        text, amount = synth_text(category, i)
        unauth = int(category in ['UPI_FRAUD','CARD_FRAUD','UNAUTHORIZED_TRANSACTION'] and random.random() < 0.72)
        # Create some legitimate/ambiguous cases so keywords alone are not sufficient.
        if category in ['OTP_SCAM','FAKE_KYC','PHISHING'] and i % 11 == 0:
            unauth = 0
        sev = random.choices([1,2,3,4], weights=[12,35,40,13])[0]
        if category in ['CARD_FRAUD','UNAUTHORIZED_TRANSACTION','UPI_FRAUD'] and i % 5 == 0:
            sev = random.choice([3,4])
        rows.append({
            'complaint_id': f'SYN-{category}-{i+1:04d}',
            'complaint_text': text,
            'category': category,
            'product': 'Digital Payment / Banking',
            'issue': category,
            'sub_issue': 'Synthetic scenario',
            'company_response': '',
            'company': 'Synthetic Scenario',
            'state': 'IN',
            'submitted_via': 'Synthetic',
            'timely_response': '',
            'consumer_disputed': '',
            'transaction_amount': float(amount),
            'payment_method': random.choice(methods),
            'unauthorized_transaction': unauth,
            'severity': sev,
            'sentiment': random.choice(['negative','negative','neutral']),
            'source': 'SYNTHETIC',
            'created_at': pd.Timestamp.now().normalize()
        })

SYN = pd.DataFrame(rows)

real_keep = REAL[[
 'Complaint ID','complaint_text','category','Product','Issue','Sub-issue',
 'Company public response','Company','State','Submitted via','Timely response?',
 'transaction_amount','payment_method','unauthorized_transaction',
 'severity','sentiment','source','created_at'
]].rename(columns={
 'Complaint ID':'complaint_id','Product':'product','Issue':'issue','Sub-issue':'sub_issue',
 'Company public response':'company_response','Timely response?':'timely_response',
 'Consumer disputed?':'consumer_disputed','State':'state','Submitted via':'submitted_via'
})

# Keep all available real narrative records and 3,000 synthetic records.
hybrid = pd.concat([real_keep, SYN], ignore_index=True)
hybrid = hybrid.drop_duplicates(subset=['complaint_id']).sample(frac=1, random_state=42).reset_index(drop=True)

# Ensure a bounded, useful dataset size if the source contains extra records.
if len(hybrid) > 6000:
    # Keep all synthetic rows and a deterministic random real subset.
    syn = hybrid[hybrid.source.eq('SYNTHETIC')]
    real = hybrid[hybrid.source.eq('REAL_CFPB')].sample(n=min(3000, len(hybrid[hybrid.source.eq('REAL_CFPB')])), random_state=42)
    hybrid = pd.concat([real, syn], ignore_index=True).sample(frac=1, random_state=42).reset_index(drop=True)

OUT.parent.mkdir(parents=True, exist_ok=True)
hybrid.to_csv(OUT, index=False)
print('Real narrative rows:', len(real_keep))
print('Synthetic rows:', len(SYN))
print('Final hybrid rows:', len(hybrid))
print('\nCategory distribution:')
print(hybrid['category'].value_counts())
print('\nSource distribution:')
print(hybrid['source'].value_counts())
print('\nSaved:', OUT)
